create table if not exists public.checkins (
  id bigint generated by default as identity primary key,
  week_start date not null,
  roommate text not null check (roommate in ('A','B','C','D')),
  day date not null,
  attended boolean not null default false,
  workout boolean not null default false,
  clean_food boolean not null default false,
  steps integer not null default 0 check (steps >= 0),
  updated_at timestamptz not null default now(),
  unique (week_start, roommate, day)
);
create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  week_start date not null,
  roommate text not null check (roommate in ('A','B','C','D')),
  code text not null,
  done boolean not null default false,
  unique (week_start, roommate, code)
);
alter table public.checkins enable row level security;
alter table public.assignments enable row level security;
create policy "rally read checkins" on public.checkins for select to anon using (true);
create policy "rally write checkins" on public.checkins for insert to anon with check (true);
create policy "rally edit checkins" on public.checkins for update to anon using (true) with check (true);
create policy "rally read assignments" on public.assignments for select to anon using (true);
create policy "rally write assignments" on public.assignments for insert to anon with check (true);
create policy "rally edit assignments" on public.assignments for update to anon using (true) with check (true);
